import java.awt.*;
import java.time.ZoneId;
import java.util.*;
import java.util.List;

@ApplicationScoped
@Slf4j
public class DiscordEventUIApplicationAdapter implements EventUIApplicationPort {
  private final DiscordBot bot;
  private final EventApplicationPort eventApplicationPort;
  private final EventStrategyService eventStrategyService;
  private final GuildService guildService;
  private final GuildMemberService guildMemberService;
  private final UserTransactionRegistry userTransactionRegistry;

  public DiscordEventUIApplicationAdapter(DiscordBot bot, EventApplicationPort eventApplicationPort, EventStrategyService eventStrategyService, GuildService guildService, GuildMemberService guildMemberService, UserTransactionRegistry userTransactionRegistry) {
    this.bot = bot;
    this.eventApplicationPort = eventApplicationPort;
    this.eventStrategyService = eventStrategyService;
    this.guildService = guildService;
    this.guildMemberService = guildMemberService;
    this.userTransactionRegistry = userTransactionRegistry;
  }

  @Override
  public void addEvent(Event event) {
    JDA api = bot.requireApi();
    log.info(event.getCategoryId());
    Category cat = api.getCategoryById(event.getCategoryId());

    if (cat == null) {
      throw new IllegalStateException(String.format("Category %s of Event %s does not exist.", event.getCategoryId(), event.getId()));
    }

    if (event.getGuild().isManageEventChannels()) {
      createChannels(event, cat);
    }

    postSignup(event);
    eventApplicationPort.save(event);
  }

  private void postSignup(Event event) {
    TextChannel textChannel = bot.requireApi().getTextChannelById(event.getSignUpChannelId());
    if (textChannel == null) {
      throw new IllegalStateException(String.format("TextChannel %s of Event %s does not exist.", event.getSignUpChannelId(), event.getId()));
    }

    EmbedBuilder embedBuilder = new EmbedBuilder();
    embedBuilder.setTitle(String.format("Event Signup for %s | %s", event.getTemplate().getName(), event.getGuild().getName()));
    embedBuilder.setDescription(generateMessageString(event));
    embedBuilder.setColor(Color.BLUE);
    embedBuilder.setFooter("Signup generated by RaidSignupBot | made by StormFox");

    Message message = textChannel.sendMessageEmbeds(
        embedBuilder.build()
    ).complete();

    event.setMessageId(message.getId());

    log.info("Message was posted to TextChannel {} of Event {} | {}", event.getSignUpChannelId(), event.getId(), event.getTemplate().getKey());

    addReactions(event, message);
  }

  private void createChannels(Event event, Category cat) {
    String day = event.getStart().atZone(ZoneId.systemDefault()).getDayOfWeek().name().substring(0, 3).toLowerCase();
    String name = (event.getTemplate().getKey() + "-" + day).toLowerCase().strip();
    if (event.getSignUpChannelId() == null) {
      TextChannel tc = cat.createTextChannel(name)
          .complete();
      event.setSignUpChannelId(tc.getId());

      log.info(
          "TextChannel {} was created for Event {} | {}, with ID {}",
          name,
          event.getId(),
          event.getTemplate().getKey(),
          event.getSignUpChannelId());
    }

    if (event.getVoiceChannelId() == null) {
      VoiceChannel vc = cat.createVoiceChannel(name)
          .complete();
      event.setVoiceChannelId(vc.getId());

      log.info(
          "VoiceChannel {} was created for Event {} | {}, with ID {}",
          name,
          event.getId(),
          event.getTemplate().getKey(),
          event.getVoiceChannelId());
    }

    event.markChannelsExist();
  }

  @Override
  public List<EventMemberSignup> closeSignup(Event event) {
    Map<String, List<String>> reactionsPerUser = new HashMap<>();
    TextChannel channel = bot.requireApi().getTextChannelById(event.getSignUpChannelId());
    if (channel == null) {
      throw new IllegalStateException(String.format("TextChannel %s of Event %s does not exist.", event.getSignUpChannelId(), event.getId()));
    }
    Message signUp = channel.retrieveMessageById(event.getMessageId()).complete();

    for (EventStrategy strategy : event.getTemplate().getStrategies()) {
      for (EventRole role : strategy.getPrimaryRoles()) {
        retrieveReaction(reactionsPerUser, signUp, role);
      }

      for (EventRole role : strategy.getUtilityRoles()) {
        retrieveReaction(reactionsPerUser, signUp, role);
      }
    }

    List<EventMemberSignup> signups = new ArrayList<>();
    reactionsPerUser.forEach((user, roles) -> {
      GuildMember gm;
      try {
        gm = guildMemberService.findGuildMemberById(user);
      } catch (Exception e) {
        log.warn("Could not find guild member with id {}", user, e);
        return;
      }
      EventMemberSignup ems = new EventMemberSignup(gm);
      roles.forEach(ems::addRoleKey);
      signups.add(ems);
    });

    return signups;
  }

  private void retrieveReaction(Map<String, List<String>> reactionsPerUser, Message signUp, EventRole role) {
    signUp.retrieveReactionUsers(resolveReactionEmoji(role.getEmojiSlug())).queue(users -> {
      if (!reactionsPerUser.containsKey(role.getKey())) {
        reactionsPerUser.put(role.getKey(), users.stream().map(ISnowflake::getId).toList());
      } else {
        reactionsPerUser.get(role.getKey()).addAll(users.stream().map(ISnowflake::getId).toList());
      }
    });
  }

  @Override
  public void deleteEvent(Event event) {
    if (event.getGuild().isManageEventChannels()) {
      deleteChannels(event);
    }
  }

  private void deleteChannels(Event event) {
    TextChannel textChannel = bot.requireApi().getTextChannelById(event.getSignUpChannelId());
    if (textChannel == null) {
      throw new IllegalStateException(String.format("TextChannel %s of Event %s does not exist.", event.getSignUpChannelId(), event.getId()));
    }

    textChannel.delete().queue();

    VoiceChannel voiceChannel = bot.requireApi().getVoiceChannelById(event.getVoiceChannelId());
    if (voiceChannel == null) {
      throw new IllegalStateException(String.format("VoiceChannel %s of Event %s does not exist.", event.getVoiceChannelId(), event.getId()));
    }

    voiceChannel.delete().queue();
  }

  private void addReactions(Event event, Message message) {
    for (EventStrategy strat : event.getTemplate().getStrategies()) {
      for (EventRole role : strat.getPrimaryRoles()) {
        message.addReaction(resolveReactionEmoji(role.getEmojiSlug())).queue();
      }

      for (EventRole role : strat.getUtilityRoles()) {
        message.addReaction(resolveReactionEmoji(role.getEmojiSlug())).queue();
      }
    }
  }

  private Emoji resolveReactionEmoji(String emojiSlug) {
    String normalized = EventRole.normalizeEmojiSlug(emojiSlug);

    if (normalized != null && normalized.startsWith(":") && normalized.endsWith(":")) {
      String customEmojiName = normalized.substring(1, normalized.length() - 1);
      List<RichCustomEmoji> customEmojis = bot.getApi().getEmojisByName(customEmojiName, true);
      if (!customEmojis.isEmpty()) {
        return customEmojis.getFirst();
      }

      throw new IllegalStateException("Unsupported emoji slug: " + emojiSlug);
    }

    return Emoji.fromFormatted(normalized);
  }

  private String generateMessageString(Event event) {
    StringBuilder builder = new StringBuilder();

    if (!(event.getGuild().getEventRoleId() == null)) {
      builder.append(event.getGuild().getEventRoleId()).append("\n");
    }

    builder.append(String.format("# :%s: %s :%s:\n", event.getTemplate().getEmojiSlug(), event.getTemplate().getName(), event.getTemplate().getEmojiSlug()));
    builder.append(String.format("## Key Host: <@%s>\n", event.getHoster().getUserId()));
    builder.append(String.format("## **Date:** <t:%s:f>\n\n", event.getStart().getEpochSecond()));
    builder.append(String.format("## Duration: %s\n\n", event.getDuration()));
    if (event.getDonation() == 0) {
      builder.append("## Donations: None");
    } else {
      builder.append(String.format("## Donations: %s Azoth", event.getDonation()));

      if (event.isDonationPerWin()) {
        builder.append(" (per win)");
      }
    }

    builder.append("\n\n");

    if (event.getTemplate().getStrategies().size() > 1) {
      builder.append("## **Strategies:**\n\n");

      for (EventStrategy strat : event.getTemplate().getStrategies()) {
        builder.append(String.format("**%s:**\n", strat.getName()));
        builder.append(generateStrategyRolesString(strat));
        builder.append(generateGuides(strat));
      }
    } else if (event.getTemplate().getStrategies().size() == 1){
      builder.append("## **Strategy:**\n");
      builder.append(generateStrategyRolesString(event.getTemplate().getStrategies().stream().toList().getFirst()));
      builder.append(generateGuides(event.getTemplate().getStrategies().stream().toList().getFirst()));
    } else {
      throw new IllegalStateException("No strategies configured for event.");
    }

    builder.append("\n\n");
    builder.append(event.getTemplate().getDetails());

    return builder.toString();
  }

  private String generateStrategyRolesString(EventStrategy strat) {
    StringBuilder builder = new StringBuilder();

    for (EventRole role : strat.getPrimaryRoles()) {
      builder.append(String.format("%s - %s\n", role.getEmojiSlug(), role.getName()));
    }

    for(EventUtilityRole role : strat.getUtilityRoles()) {
      builder.append(String.format("**UTILITY**: %s - %s (Can be done by: %s)\n",
          role.getEmojiSlug(), role.getName(), String.join(", ", role.getEligiblePrimaryRoleKeys())));
    }

    builder.append("\n");

    return builder.toString();
  }

  private String generateGuides(EventStrategy strat) {
    StringBuilder builder = new StringBuilder();

    builder.append("#### **Guides**:");

    for (String guide : strat.getGuides()) {
      builder.append(String.format("%s\n", guide));
    }

    return builder.toString();
  }
}
