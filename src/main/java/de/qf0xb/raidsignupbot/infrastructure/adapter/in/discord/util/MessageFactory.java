package de.qf0xb.raidsignupbot.infrastructure.adapter.in.discord.util;

import de.qf0xb.raidsignupbot.application.TeamGeneratorResult;
import de.qf0xb.raidsignupbot.application.service.event.EventLifecycleStage;
import de.qf0xb.raidsignupbot.domain.model.event.*;
import de.qf0xb.raidsignupbot.domain.model.event.Event;
import de.qf0xb.raidsignupbot.domain.model.template.EventRole;
import de.qf0xb.raidsignupbot.domain.model.template.EventStrategy;
import de.qf0xb.raidsignupbot.domain.model.template.EventUtilityRole;
import de.qf0xb.raidsignupbot.infrastructure.adapter.in.discord.util.DiscordEmojiResolver;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;
import net.dv8tion.jda.api.EmbedBuilder;
import net.dv8tion.jda.api.entities.emoji.Emoji;

import java.awt.*;
import java.util.List;
import java.util.LinkedHashSet;
import java.util.Set;
import java.util.stream.Collectors;

@ApplicationScoped
public class MessageFactory {
  @Inject
  DiscordEmojiResolver emojiResolver;

  public EmbedBuilder buildSignupEmbed(Event event) {
    EmbedBuilder embedBuilder = new EmbedBuilder();
    embedBuilder.setTitle(String.format("Event Signup for %s | %s", event.getTemplate().getName(), event.getGuild().getName()));
    embedBuilder.setColor(Color.BLUE);
    embedBuilder.setFooter("Signup generated by onyxguildbot | made by StormFox");
    embedBuilder.setDescription(buildSignupDescription(event));
    return embedBuilder;
  }

  public String buildSignupPing(Event event) {
    if (event.getGuild().getEventRoleId() == null || event.getGuild().getEventRoleId().isBlank()) {
      return "";
    }

    return "<@&" + event.getGuild().getEventRoleId() + ">";
  }

  public EmbedBuilder buildReminderEmbed(Event event, EventLifecycleStage stage) {
    EmbedBuilder embedBuilder = new EmbedBuilder();
    embedBuilder.setTitle(buildReminderTitle(event, stage));
    embedBuilder.setColor(buildReminderColor(stage));
    embedBuilder.setDescription(buildReminderDescription(event, stage));
    embedBuilder.addField("Raid", event.getTemplate().getName() + " | " + event.getGuild().getName(), false);
    embedBuilder.addField("Voice Channel", buildVoiceChannelLink(event), false);
    embedBuilder.setFooter("Reminder generated by onyxguildbot | made by StormFox");
    return embedBuilder;
  }

  public String buildMentionList(List<? extends EventMemberSignup> signups) {
    return signups.stream()
        .map(signup -> signup.getGuildMember().getUserId())
        .distinct()
        .map(userId -> "<@" + userId + ">")
        .collect(Collectors.joining(" "));
  }

  private String buildVoiceChannelLink(Event event) {
    if (event.getVoiceChannelId() == null || event.getVoiceChannelId().isBlank()) {
      return "voice channel";
    }

    return "<#" + event.getVoiceChannelId() + ">";
  }

  private String buildReminderTitle(Event event, EventLifecycleStage stage) {
    return switch (stage) {
      case ONE_HOUR_BEFORE -> String.format("Raid reminder: 1 hour left for %s", event.getTemplate().getName());
      case THIRTY_MINUTES_BEFORE -> String.format("Raid reminder: 30 minutes left for %s", event.getTemplate().getName());
      case FIFTEEN_MINUTES_BEFORE -> String.format("Urgent raid reminder: 15 minutes left for %s", event.getTemplate().getName());
      case ONE_HOUR_AFTER -> String.format("Raid follow-up for %s", event.getTemplate().getName());
    };
  }

  private String buildReminderDescription(Event event, EventLifecycleStage stage) {
    String voiceChannelLink = buildVoiceChannelLink(event);
    return switch (stage) {
      case ONE_HOUR_BEFORE -> String.format(
          "One hour left for **%s** on **%s**. Everyone assigned to the raid must be in %s no later than 15 minutes before start.",
          event.getTemplate().getName(),
          event.getGuild().getName(),
          voiceChannelLink);
      case THIRTY_MINUTES_BEFORE -> String.format(
          "30 minutes left for **%s** on **%s**. Start joining %s, get online, and get ready.",
          event.getTemplate().getName(),
          event.getGuild().getName(),
          voiceChannelLink);
      case FIFTEEN_MINUTES_BEFORE -> String.format(
          "15 minutes left for **%s** on **%s**. Join %s now.",
          event.getTemplate().getName(),
          event.getGuild().getName(),
          voiceChannelLink);
      case ONE_HOUR_AFTER -> String.format(
          "The raid for **%s** on **%s** should be over now. Thanks for coming.",
          event.getTemplate().getName(),
          event.getGuild().getName());
    };
  }

  private Color buildReminderColor(EventLifecycleStage stage) {
    return switch (stage) {
      case ONE_HOUR_BEFORE -> new Color(70, 130, 180);
      case THIRTY_MINUTES_BEFORE -> new Color(255, 170, 0);
      case FIFTEEN_MINUTES_BEFORE -> new Color(220, 53, 69);
      case ONE_HOUR_AFTER -> new Color(108, 117, 125);
    };
  }

  public String buildSignupDescription(Event event) {
    StringBuilder builder = new StringBuilder();

    builder.append(String.format("# :%s: %s :%s:\n", event.getTemplate().getEmojiSlug(), event.getTemplate().getName(), event.getTemplate().getEmojiSlug()));
    builder.append(String.format("## Key Host: <@%s>\n", event.getHoster().getUserId()));
    builder.append(String.format("## **Date:** <t:%s:f>\n\n", event.getStart().getEpochSecond()));
    builder.append(String.format("## Duration: %s\n\n", event.getDuration()));
    if (event.getDonation() == 0) {
      builder.append("## Donations: None");
    } else {
      builder.append(String.format("## Donations: %s Azoth", event.getDonation()));

      if (event.isDonationPerWin()) {
        builder.append(" (per win)");
      }
    }

    builder.append("\n\n");

    if (event.getTemplate().getStrategies().size() > 1) {
      builder.append("## **Strategies:**\n\n");

      for (EventStrategy strat : event.getTemplate().getStrategies()) {
        builder.append(String.format("**%s:**\n", strat.getName()));
        builder.append(buildStrategyRolesString(strat));
        builder.append(buildGuides(strat));
        builder.append("\n\n");
      }
    } else if (event.getTemplate().getStrategies().size() == 1) {
      builder.append("## **Strategy:**\n");
      EventStrategy strategy = event.getTemplate().getStrategies().stream().toList().getFirst();
      builder.append(buildStrategyRolesString(strategy));
      builder.append(buildGuides(strategy));
      builder.append("\n\n");
    } else {
      throw new IllegalStateException("No strategies configured for event.");
    }

    builder.append(String.format(
        "%s - Backup (low priority: -%d)\n\n",
        EventMemberSignup.BACKUP_EMOJI,
        EventMemberSignup.BACKUP_PRIORITY_PENALTY));

    builder.append("## **How to join:**\n");
    builder.append("1. React with the emoji of your choice to the message below.\n");
    builder.append("2. Wait for the bot to assign you a role.\n");
    builder.append("3. You automatically get the raider role when assigned to a position or assigned backup.\n");

    builder.append("\n\n");
    builder.append("## **Rules:**\n");
    builder.append("1. Notify the hoster **ASAP** if you are not able to make it anymore.\n");
    builder.append("2. Join the channel and be on guild island **at least** 15 minutes before start.\n");
    builder.append("3. If you do not show by this time, you will get a warning and a backup will take the spot.\n");

    return builder.toString();
  }

  private String buildStrategyRolesString(EventStrategy strat) {
    StringBuilder builder = new StringBuilder();

    for (EventRole role : strat.getPrimaryRoles()) {
      builder.append(String.format("%s - %s\n", resolveEmoji(role.getEmojiSlug()), role.getName()));
    }

    for (EventUtilityRole role : strat.getUtilityRoles()) {
      builder.append(String.format("**UTILITY**: %s - %s (Can be done by: %s)\n",
          resolveEmoji(role.getEmojiSlug()),
          role.getName(),
          formatEligiblePrimaryRoleKeys(strat, role)));
    }

    return builder.toString();
  }

  private String buildGuides(EventStrategy strat) {
    StringBuilder builder = new StringBuilder();
    if (strat.getGuides().isEmpty()) {
      return "";
    }

    builder.append("**Guides**:");

    for (String guide : strat.getGuides()) {
      builder.append(String.format("%s\n", guide));
    }

    builder.append("\n\n");

    return builder.toString();
  }

  // TEAMS
  public String buildTeams(Event event, TeamGeneratorResult result) {
    StringBuilder sb = new StringBuilder();
    if(result.teams().isEmpty()) {
      sb.append("**No teams could be generated.**\n");
    }

    int count = 1;
    for(EventTeam team : result.teams()) {
      sb.append(buildTeam(team, count));
      count++;
    }

    if (!result.unmatchedSignups().isEmpty()) {
      sb.append("Players without a team were asked privately about backup availability.\n");
    }
    return sb.toString();
  }

  public String buildTeams(Event event) {
    return buildTeams(event, new TeamGeneratorResult(event.getTeams(), List.of()));
  }

  public String buildTeam(EventTeam eventTeam, int count) {
    StringBuilder sb = new StringBuilder();
    sb.append(String.format("**Team %s: %s Strategy**", count, eventTeam.getStrategy().getName()));
    for(EventSlot slot : eventTeam.getSlots()) {
      sb.append(String.format("\n%s (%s): <@%s>", slot.getEmojiSlug(), slot.getRoleName(), slot.getMember().getUserId()));
    }

    for (EventUtilityAssignment utilityAssignment : eventTeam.getUtilityAssignments()) {
      if (utilityAssignment.isAssigned()) {
        sb.append(String.format(
            "\n%s (%s): <@%s>",
            utilityAssignment.getEmojiSlug(),
            utilityAssignment.getRoleName(),
            utilityAssignment.getMember().getUserId()));
      }
    }
    sb.append("\n\n");

    return sb.toString();
  }

  private String formatEligiblePrimaryRoleKeys(EventStrategy strategy, EventUtilityRole utilityRole) {
    Set<String> emojiSlugs = new LinkedHashSet<>();

    for (String roleKey : utilityRole.getEligiblePrimaryRoleKeys()) {
      strategy.getPrimaryRoles().stream()
          .filter(role -> role.getKey().equals(roleKey))
          .findFirst()
          .map(EventRole::getEmojiSlug)
          .map(this::resolveEmoji)
          .ifPresentOrElse(
              emojiSlugs::add,
              () -> emojiSlugs.add(EventMemberSignup.BACKUP_ROLE_KEY.equals(roleKey)
                  ? EventMemberSignup.BACKUP_EMOJI
                  : roleKey));
    }

    return emojiSlugs.isEmpty() ? "[]" : String.join(", ", emojiSlugs);
  }

  private String resolveEmoji(String emojiSlug) {
    Emoji emoji = emojiResolver.resolve(emojiSlug);
    return emoji.getFormatted();
  }
}
