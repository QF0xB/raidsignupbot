package de.qf0xb.raidsignupbot.event.domain.model;

import de.qf0xb.raidsignupbot.guild.domain.model.Guild;
import de.qf0xb.raidsignupbot.guild.domain.model.GuildMember;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.RequiredArgsConstructor;
import lombok.Setter;

import java.time.Instant;
import java.util.HashSet;
import java.util.Set;

@AllArgsConstructor
@Getter
@Setter
public class Event {
  private final Long id; // Generated by persistence layer
  private final EventTemplate template;
  private final Guild guild;
  private final GuildMember hoster;

  @Setter
  private int donation;

  private boolean signupOpen = true;

  @Setter
  private Instant start;

  @Setter
  private Instant end;

  private final Set<EventTeam> teams = new HashSet<>();

  public Event(EventTemplate template, Guild guild, GuildMember hoster, int donation, Instant start, Instant end) {
    this.id = null;
    this.template = template;
    this.guild = guild;
    this.hoster = hoster;
    this.donation = donation;
    this.start = start;
    this.end = end;
  }

  public void closeSignup() {
    this.signupOpen = false;
  }

  public boolean isOver() {
    return end.isBefore(Instant.now());
  }
}
