-- Raider roles the bot granted to assigned players, so it only removes roles it added itself.
-- No foreign key to event: grants of a deleted event are released right before the deletion.
CREATE TABLE raider_role_grant
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    event_id      BIGINT                                  NOT NULL,
    server_id     VARCHAR(255)                            NOT NULL,
    user_id       VARCHAR(255)                            NOT NULL,
    role_id       VARCHAR(255)                            NOT NULL,
    backup        BOOLEAN                                 NOT NULL,
    release_after TIMESTAMPTZ                             NOT NULL,
    CONSTRAINT pk_raider_role_grant PRIMARY KEY (id),
    CONSTRAINT uc_raider_role_grant_event_user UNIQUE (event_id, user_id)
);

CREATE INDEX idx_raider_role_grant_holder ON raider_role_grant (server_id, user_id, role_id);
